
from reportlab.lib.pagesizes import A4

from reportlab.platypus import (
    SimpleDocTemplate,
    Paragraph,
    Spacer,
    Table,
    TableStyle
)
from reportlab.lib import colors
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.lib.enums import TA_CENTER
from reportlab.lib.units import inch
from reportlab.lib.colors import HexColor
from xml.sax.saxutils import escape
from datetime import datetime
import os


def generate_report(
    candidate_name,
    match_score,
    matched_skills,
    missing_skills,
    ai_analysis,
    output_path="outputs/resume_analysis_report.pdf"
):

    os.makedirs(os.path.dirname(output_path) or ".", exist_ok=True)

    document = SimpleDocTemplate(
        output_path,
        pagesize=A4,
        rightMargin=45,
        leftMargin=45,
        topMargin=45,
        bottomMargin=45
    )

    styles = getSampleStyleSheet()

    title_style = ParagraphStyle(
        "CustomTitle",
        parent=styles["Title"],
        fontSize=22,
        textColor=HexColor("#17365D"),
        alignment=TA_CENTER,
        spaceAfter=15
    )

    heading_style = ParagraphStyle(
        "SectionHeading",
        parent=styles["Heading2"],
        textColor=HexColor("#17365D"),
        spaceBefore=12,
        spaceAfter=8
    )

    normal_style = styles["BodyText"]

    story = []

    # Report title
    story.append(Paragraph("RESUMIND", title_style))
    story.append(
        Paragraph("AI-Powered Resume Analysis Report", styles["Heading2"])
    )
    story.append(Spacer(1, 15))

    # Candidate details
    story.append(Paragraph("Candidate Information", heading_style))
    story.append(Paragraph(
        f"Candidate Name: {escape(str(candidate_name))}",
        normal_style
    ))
    story.append(Paragraph(
        f"Report Date: {datetime.now().strftime('%d-%m-%Y')}",
        normal_style
    ))

    story.append(Spacer(1, 15))

    # Matching score
    story.append(Paragraph("Resume Matching Score", heading_style))

    score_table = Table(
        [["Overall Match Score", f"{match_score}%"]],
        colWidths=[3.5 * inch, 1.5 * inch]
    )

    score_table.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, -1), HexColor("#DCE6F1")),
        ("TEXTCOLOR", (0, 0), (-1, -1), HexColor("#17365D")),
        ("FONTNAME", (0, 0), (-1, -1), "Helvetica-Bold"),
        ("FONTSIZE", (0, 0), (-1, -1), 12),
        ("ALIGN", (0, 0), (-1, -1), "CENTER"),
        ("BOX", (0, 0), (-1, -1), 1, colors.grey),
        ("PADDING", (0, 0), (-1, -1), 12)
    ]))

    story.append(score_table)

    # Matched skills
    story.append(Paragraph("Matched Skills / Keywords", heading_style))

    if matched_skills:
        for skill in matched_skills:
            story.append(Paragraph(f"• {escape(str(skill))}", normal_style))
    else:
        story.append(Paragraph("No matching keywords found.", normal_style))

    # Missing skills
    story.append(Paragraph("Missing Skills / Keywords", heading_style))

    if missing_skills:
        for skill in missing_skills:
            story.append(Paragraph(f"• {escape(str(skill))}", normal_style))
    else:
        story.append(Paragraph("No missing keywords found.", normal_style))

    # AI analysis
    story.append(Paragraph("AI Resume Analysis", heading_style))

    analysis_text = escape(str(ai_analysis)).replace("\n", "<br/>")
    story.append(Paragraph(analysis_text, normal_style))

    # Footer
    story.append(Spacer(1, 25))
    story.append(Paragraph(
        "Generated by Resumind",
        ParagraphStyle(
            "Footer",
            parent=normal_style,
            alignment=TA_CENTER,
            textColor=colors.grey
        )
    ))

    document.build(story)

    return output_path


if __name__ == "__main__":

    path = generate_report(
        candidate_name="Aarav Sharma",
        match_score=80,
        matched_skills=["Python", "Java", "SQL"],
        missing_skills=["Communication", "Leadership"],
        ai_analysis=(
            "The candidate demonstrates good programming fundamentals. "
            "Improving communication and leadership skills may strengthen "
            "the application."
        )
    )

    print("PDF report generated successfully!")
    print("Saved at:", path)
